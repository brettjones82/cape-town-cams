#!/usr/bin/env python3
"""Builds favicon.svg from the ASCII skyline below: Devil's Peak, Table Mountain, Lion's Head
(as seen from the city). '#' = mountain, '~' = sea, 'o' = optional dot. Run: python3 scripts/favicon.py"""
ART = r"""
.....#..........................
.....##..############...........
....###.##############..........
....##################......#...
....###################....###..
....###################....###..
...#####################...###..
...#####################..#####.
...######################.#####.
..##############################
..##############################
..##############################
.###############################
.###############################
################################
################################
################################
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
"""
COLOURS = {"#": "#5cc8d6", "~": "#3f7f88", "o": "#ff4d3d"}
rows = [r for r in ART.strip("\n").splitlines()]
w, h = len(rows[0]), len(rows)
pad = (w - h) // 2  # centre vertically in a square
rects = []
for y, row in enumerate(rows):
    x = 0
    while x < len(row):
        c = row[x]
        if c in COLOURS:  # merge runs of the same character into one rect
            start = x
            while x < len(row) and row[x] == c:
                x += 1
            rects.append(f'<rect x="{start}" y="{y + pad}" width="{x - start}" height="1" fill="{COLOURS[c]}"/>')
        else:
            x += 1
svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="-2 -2 {w + 4} {w + 4}" shape-rendering="crispEdges">\n'
       f'  <!-- Generated by scripts/favicon.py from ASCII art: Devil\'s Peak, Table Mountain, Lion\'s Head -->\n'
       f'  <rect x="-2" y="-2" width="{w + 4}" height="{w + 4}" rx="7" fill="#0e1214"/>\n  '
       + "\n  ".join(rects) + "\n</svg>\n")
open("favicon.svg", "w").write(svg)
print("\n".join(rows))
